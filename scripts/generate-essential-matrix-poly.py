#!/usr/bin/env python3
# Generates colmap-rust/src/estimators/solvers/essential_matrix_poly{1,2,3}.rs and
# essential_matrix_coeffs.rs from COLMAP's generated headers
# src/colmap/estimators/solvers/essential_matrix_poly.h (the 10 x 20 polynomial matrix A of the
# over-determined five-point solver) and essential_matrix_coeffs.h (the 11 coefficients of its
# tenth-degree determinant polynomial). Same operation order as colmap-sharp's
# scripts/generate-essential-matrix-poly.py (EssentialMatrixPolynomials.*.cs): each
# assignment is copied term for term; only `coeffs(k)` becomes `coeffs[k]` and `3.` becomes
# `3.0`. The functions are #[rustfmt::skip] so the generated layout (and the
# 800-non-empty-line limit) holds.
#
# Usage: scripts/fetch-reference.sh && python3 scripts/generate-essential-matrix-poly.py
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "cpp-reference" / "src" / "colmap" / "estimators" / "solvers"
if not SRC.exists():
    SRC = ROOT.parent.parent.parent / "cpp-reference" / "src" / "colmap" / "estimators" / "solvers"
OUT = ROOT / "colmap-rust" / "src" / "estimators" / "solvers"
PARTS = 3


def statements(path, target):
    """The `target[...] = ...;` / `target(...) = ...;` assignments of a header, in order."""
    text = path.read_text()
    pattern = re.compile(r"^\s*(" + target + r"[\[(]\d+[\])]\s*=[^;]*;)", re.M | re.S)
    out = []
    for m in pattern.finditer(text):
        stmt = " ".join(m.group(1).split())
        stmt = re.sub(r"coeffs\((\d+)\)", r"coeffs[\1]", stmt)
        # C++'s `3.` literal spelled `3.0`.
        stmt = re.sub(r"\b(\d+)\.(?!\d)", r"\1.0", stmt)
        out.append(stmt)
    return out


def wrap(stmt, width=96):
    """Breaks one statement after operators so lines stay under `width` columns."""
    words = stmt.split(" ")
    lines, line = [], "    "
    for w in words:
        if len(line) + len(w) + 1 > width and line.strip():
            lines.append(line.rstrip())
            line = "        "
        line += w + " "
    lines.append(line.rstrip())
    return "\n".join(lines)


HEADER = """//! GENERATED by scripts/generate-essential-matrix-poly.py from COLMAP's
//! `colmap/estimators/solvers/{src}`. Do not edit by hand; rerun the script.
//!
//! {what}
//! Called from [`super::essential_matrix`] (the over-determined five-point path). Port of
//! colmap-sharp's `{cs}`, operation order kept term for term.
"""

POLY_FN = """
/// Part {part} of {parts} of the 10 x 20 polynomial matrix A: the verbatim assignments of
/// `essential_matrix_poly.h`. `a` is A column-major; `e` is the 9 x 4 null-space basis E
/// column-major, with `e2` and `e3` its element-wise squares and cubes.
#[rustfmt::skip]
pub(super) fn fill_polynomial_matrix_part{part}(a: &mut [f64; 200], e: &[f64; 36], e2: &[f64; 36], e3: &[f64; 36]) {{
{body}
}}
"""

COEFFS_FN = """
/// The 11 coefficients of the tenth-degree determinant polynomial of the 3 x 3 polynomial
/// matrix B: the verbatim assignments of `essential_matrix_coeffs.h`. `b` is the 13 x 3
/// matrix B column-major.
#[rustfmt::skip]
pub(super) fn compute_determinant_coefficients(b: &[f64; 39], coeffs: &mut [f64; 11]) {{
{body}
}}
"""


def main():
    poly = statements(SRC / "essential_matrix_poly.h", "a")
    coeffs = statements(SRC / "essential_matrix_coeffs.h", "coeffs")
    if len(poly) != 200 or len(coeffs) != 11:
        sys.exit(f"unexpected statement counts: {len(poly)} poly, {len(coeffs)} coeffs")
    size = (len(poly) + PARTS - 1) // PARTS
    for part in range(PARTS):
        chunk = poly[part * size:(part + 1) * size]
        # e2/e3 are unused in parts that never reference them; keep the signature uniform.
        body = "\n".join(wrap(s) for s in chunk)
        what = (f"Part {part + 1} of {PARTS} of the coefficients of the ten cubic constraints (the\n"
                "//! determinant and the trace constraint 2 E E^T E - tr(E E^T) E = 0) on the null-space\n"
                "//! combination x E0 + y E1 + z E2 + E3 (Nister, PAMI 2004).")
        text = HEADER.format(src="essential_matrix_poly.h", what=what,
                             cs=f"EssentialMatrixPolynomials.Poly{part + 1}.cs")
        text += POLY_FN.format(part=part + 1, parts=PARTS, body=body)
        (OUT / f"essential_matrix_poly{part + 1}.rs").write_text(text)
    what = ("The tenth-degree polynomial in z whose roots are the solutions (Nister's equation\n"
            "//! 14).")
    text = HEADER.format(src="essential_matrix_coeffs.h", what=what,
                         cs="EssentialMatrixPolynomials.Coeffs.cs")
    text += COEFFS_FN.format(body="\n".join(wrap(s) for s in coeffs))
    (OUT / "essential_matrix_coeffs.rs").write_text(text)


if __name__ == "__main__":
    main()
