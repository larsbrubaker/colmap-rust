// Rust-only tests (PoseLib's relpose_5pt has no unit test; COLMAP tests it only through
// EssentialMatrixFivePointEstimator, not yet ported) of
// colmap_rust::estimators::solvers::poselib::relpose_5pt. Tier B: on random minimal problems
// every returned E has unit norm and satisfies the five epipolar constraints, and the true E
// is among the solutions up to sign (the solution set does not depend on the null-space
// basis, docs/CPP_DIVERGENCES.md entry 250).

use colmap_rust::estimators::solvers::poselib::relpose_5pt::relpose_5pt;
use colmap_rust::geometry::essential_matrix::essential_matrix_from_pose;
use colmap_rust::geometry::Rigid3d;
use colmap_rust::linalg::{AngleAxisd, Matrix3d, Vector3d};
use colmap_rust::math::random::{random_uniform_real, set_prng_seed};
use colmap_rust::math::random_eigen::random_eigen_vector3d;

/// A relative pose with a rotation of at most 0.5 rad and a unit baseline, so both cameras
/// see the points generated by [`random_problem`] (a random rotation can turn camera 2 away
/// from every point).
fn random_cam2_from_cam1() -> Rigid3d {
    let axis = random_eigen_vector3d().normalized();
    let angle = random_uniform_real(-0.5, 0.5);
    let rotation = AngleAxisd::new(angle, axis).to_quaternion();
    Rigid3d::new(rotation, random_eigen_vector3d().normalized())
}

/// Five correspondences of points in front of both cameras, as unit bearings.
fn random_problem(cam2_from_cam1: &Rigid3d) -> (Vec<Vector3d>, Vec<Vector3d>) {
    let mut x1 = Vec::new();
    let mut x2 = Vec::new();
    while x1.len() < 5 {
        let px = random_uniform_real(-1.0, 1.0);
        let py = random_uniform_real(-1.0, 1.0);
        let depth = random_uniform_real(2.0, 6.0);
        let point1 = Vector3d::new(px, py, 1.0) * depth;
        let point2 = *cam2_from_cam1 * point1;
        if point2.z < 0.5 {
            continue;
        }
        x1.push(point1.normalized());
        x2.push(point2.normalized());
    }
    (x1, x2)
}

fn max_abs_diff(a: &Matrix3d, b: &Matrix3d) -> f64 {
    a.to_column_major()
        .iter()
        .zip(b.to_column_major())
        .fold(0.0_f64, |acc, (x, y)| acc.max((x - y).abs()))
}

#[test]
fn rust_only_recovers_true_essential_matrix() {
    set_prng_seed(0);
    for _ in 0..100 {
        let cam2_from_cam1 = random_cam2_from_cam1();
        let (x1, x2) = random_problem(&cam2_from_cam1);

        let true_e = essential_matrix_from_pose(&cam2_from_cam1);
        let true_e = true_e * (1.0 / true_e.norm());

        let mut models = Vec::new();
        let num_models = relpose_5pt(&x1, &x2, &mut models);
        assert_eq!(num_models, models.len());
        assert!(num_models <= 10);

        let mut found = false;
        for e in &models {
            assert!((e.norm() - 1.0).abs() < 1e-10);
            for (a, b) in x1.iter().zip(&x2) {
                assert!(b.dot(*e * *a).abs() < 1e-8);
            }
            let distance = max_abs_diff(e, &true_e).min(max_abs_diff(&(*e * -1.0), &true_e));
            // Up to 1e-4: a narrow field of view with a small rotation leaves some problems
            // ill-conditioned (observed up to 2e-5 off; well-conditioned ones agree to 1e-15).
            // colmap-sharp's EssentialMatrixFivePointEstimator test allows COLMAP's 5e-3.
            if distance < 1e-4 {
                found = true;
            }
        }
        assert!(found, "true E not among {num_models} solutions");
    }
}

#[test]
fn rust_only_appends_to_existing_models() {
    set_prng_seed(1);
    let cam2_from_cam1 = random_cam2_from_cam1();
    let (x1, x2) = random_problem(&cam2_from_cam1);

    let mut models = vec![Matrix3d::identity()];
    let num_models = relpose_5pt(&x1, &x2, &mut models);
    assert!(num_models > 0);
    assert_eq!(models.len(), num_models + 1);
    assert_eq!(models[0], Matrix3d::identity());
}
