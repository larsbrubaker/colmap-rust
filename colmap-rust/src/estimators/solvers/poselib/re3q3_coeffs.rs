//! fa7280fee27f97aff31ae7f98bab7f583fac7d08): from the 3 x 7 matrix `P` left after one variable
//! is eliminated, the two rows of the 3 x 3 polynomial matrix `M(x)` that the back substitution
//! reads, and the degree-8 polynomial `det(M(x))`. Split out of [`super::re3q3`] (which owns
//! the solver) because the generated expressions alone are most of PoseLib's file. Port of the
//! middle of colmap-sharp's `Re3q3.Solve`, operation order kept term for term.

/// The coefficients of rows 1 and 2 of `M(x)` (PoseLib's `a11..a110` and `a21..a210`) and
/// `det(M(x))`, constant first.
pub(super) struct Elimination {
    /// `a11..a110`.
    pub a1: [f64; 10],
    /// `a21..a210`.
    pub a2: [f64; 10],
    /// `det(M(x))`, `c[k]` the coefficient of `x^k`.
    pub c: [f64; 9],
}

/// `p` is the 3 x 7 matrix `P` in column-major order (`P(r, c) = p[r + 3 c]`).
